def main():
    Base.metadata.create_all(__import__("db").engine)
    with SessionLocal() as session:
        created = 0
        for rule in RULES:
            try:
                create_violation_type(
                    session,
                    name=rule["name"],
                    category=ViolationCategory(rule["cat"]),
                    section_code=rule["code"],
                    description=rule.get("notes"),
                    offense_levels=rule["levels"],
                    escalation_window_days=365,
                    actor="seed_script",
                )
                created += 1
            except Exception as e:
                print(f"  SKIP {rule['code']}: {e}")
        print(f"\nCreated {created} violation types from rulebook.")


if __name__ == "__main__":
    main()
