# Shorthand: _l(offense_number, description, suspension_days=None, is_dismissal=False, requires_payment=False)
def _l(n, desc, susp=None, dismiss=False, pay=False):
    return {
        "offense_number": n, "penalty_description": desc,
        "suspension_days": susp, "is_dismissal": dismiss, "requires_payment": pay,
    }

# Common patterns
